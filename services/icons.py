# ══════════════════════════════════════════════════════════════════════════════
#  APPLY SPANS
# ══════════════════════════════════════════════════════════════════════════════
exceptions = ["font_family", "font_weight", "span", "exceptions", "apply_span"]


def apply_span() -> None:
    global_dict = globals()
    keys = [*global_dict]
    for key in keys:
        if key not in exceptions and not key.startswith("__"):
            val = global_dict[key]
            if isinstance(val, str) and "&#x" in val:
                global_dict[key] = f"{span}{val}</span>"


apply_span()